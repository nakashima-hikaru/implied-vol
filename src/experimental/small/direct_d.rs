#[inline]
fn base(h: Pair) -> Pair {
    let k = (2.0 * h.hi).floor() as usize;
    let x = sub(h, Pair::from((2.0 * k as f64 + 1.0) * 0.25));
    let c = &COEFF[k];
    let n = DEGREE[k];
    let mut p = c[n];
    for i in (3..n).rev() {
        p = fma(p, x.hi, c[i]);
    }
    let mut lo = 0.0;
    for i in (0..3).rev() {
        let product = p * x.hi;
        let mut err = fma(p, x.hi, -product) + p * x.lo;
        let sum = product + c[i];
        let z = sum - product;
        err += ((product - (sum - z)) + (c[i] - z)) + LOW[k][i];
        lo = fma(lo, x.hi, err);
        p = sum;
    }
    Pair::new(p, lo)
}

#[inline]
pub(super) fn evaluate(h: Pair, t: Pair) -> Pair {
    let d0 = base(h);
    if t.hi <= 0.0625 {
        odd_series::<6>(h, t, d0)
    } else if t.hi <= 0.25 {
        odd_series::<9>(h, t, d0)
    } else {
        odd_series::<12>(h, t, d0)
    }
}
#[inline]
fn odd_series<const TERMS: usize>(h: Pair, t: Pair, d0: Pair) -> Pair {
    // I3=(h^2+3)*I1-1. Preserve the argument and D0 lows before the
    // higher moments use ordinary FMA; their errors are scaled by t^(2j).
    let H = h.hi * h.hi;
    let Hlo = fma(h.hi, h.hi, -H) + 2.0 * h.hi * h.lo;
    let a = H + 3.0;
    let alo = ((H - a) + 3.0) + Hlo;
    let i3 = fma(a, d0.hi, -1.0) + fma(a, d0.lo, alo * d0.hi);
    let mut prev = d0.hi;
    let mut cur = i3;
    let mut cs = [0.0; TERMS];
    cs[1] = i3 * (1.0 / 6.0);
    // I_(n+2)=(h^2+2n+1)*I_n-n(n-1)*I_(n-2), for odd n>=3.
    // Const term counts keep the reciprocal factorials and short recurrence
    // stages fixed. The source certificate checks their represented bits.
    if TERMS > 2 {
        let next = fma(H + 7.0, cur, -6.0 * prev);
        prev = cur;
        cur = next;
        cs[2] = cur * 0.008333333333333333;
    }
    if TERMS > 3 {
        let next = fma(H + 11.0, cur, -20.0 * prev);
        prev = cur;
        cur = next;
        cs[3] = cur * 0.0001984126984126984;
    }
    if TERMS > 4 {
        let next = fma(H + 15.0, cur, -42.0 * prev);
        prev = cur;
        cur = next;
        cs[4] = cur * 2.7557319223985893e-06;
    }
    if TERMS > 5 {
        let next = fma(H + 19.0, cur, -72.0 * prev);
        prev = cur;
        cur = next;
        cs[5] = cur * 2.505210838544172e-08;
    }
    if TERMS > 6 {
        let next = fma(H + 23.0, cur, -110.0 * prev);
        prev = cur;
        cur = next;
        cs[6] = cur * 1.6059043836821613e-10;
    }
    if TERMS > 7 {
        let next = fma(H + 27.0, cur, -156.0 * prev);
        prev = cur;
        cur = next;
        cs[7] = cur * 7.647163731819816e-13;
    }
    if TERMS > 8 {
        let next = fma(H + 31.0, cur, -210.0 * prev);
        prev = cur;
        cur = next;
        cs[8] = cur * 2.8114572543455206e-15;
    }
    if TERMS > 9 {
        let next = fma(H + 35.0, cur, -272.0 * prev);
        prev = cur;
        cur = next;
        cs[9] = cur * 8.22063524662433e-18;
    }
    if TERMS > 10 {
        let next = fma(H + 39.0, cur, -342.0 * prev);
        prev = cur;
        cur = next;
        cs[10] = cur * 1.9572941063391263e-20;
    }
    if TERMS > 11 {
        let next = fma(H + 43.0, cur, -420.0 * prev);
        cur = next;
        cs[11] = cur * 3.868170170630684e-23;
    }
    let T = t.hi * t.hi;
    let mut r = 0.0;
    for j in (1..TERMS).rev() {
        r = fma(r, T, cs[j]);
    }
    add(d0, Pair::from(T * r))
}

