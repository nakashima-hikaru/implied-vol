#[test]
fn default_near_atm_calculation_selects_hybrid() {
    let input = ImpliedBlackVolatilityNormalised::builder()
        .log_moneyness(-1e-200)
        .normalised_price(1e-201)
        .build()
        .unwrap();
    let default = input.calculate::<DefaultSpecialFn>().unwrap();
    assert!(default.is_finite() && default > 0.0);
    assert_eq!(
        default.to_bits(),
        input.calculate_with::<Hybrid>().unwrap().to_bits()
    );
}

