//! Independent exact-input roots for the near-ATM seed and correction paths.

use implied_vol::solver::{BlackSolver, Hybrid, Jaeckel};
use implied_vol::{DefaultSpecialFn, ImpliedBlackVolatilityNormalised};

fn check<S: BlackSolver>() {
    for &[x_bits, beta_bits, root_bits, correction_bits, eta_bits] in ROOTS {
        let x = f64::from_bits(x_bits);
        let beta = f64::from_bits(beta_bits);
        let root = f64::from_bits(root_bits);
        let correction = f64::from_bits(correction_bits);
        let eta = f64::from_bits(eta_bits);
        let actual = S::implied_total_volatility(x, beta).unwrap();
        assert!(
            actual.is_finite() && actual > 0.0,
            "x={x:.17e}, beta={beta:.17e}, actual={actual}"
        );
        assert_eq!(
            actual.to_bits(),
            S::implied_total_volatility(-x, beta).unwrap().to_bits()
        );
        // The correction stores (s_star - rounded_root)/rounded_root, including
        // when the absolute sub-ulp correction would itself underflow.
        let error = ((actual - root) / root - correction).abs();
        // Keep the one-estimate precision target on the stabilized path. The
        // neighbor above its cutoff retains the existing four-estimate test
        // envelope for the unchanged Jaeckel implementation.
        let limit = if x.abs() <= f64::from_bits(0x3eb0_0000_0000_0000) {
            eta
        } else {
            4.0 * eta
        };
        assert!(
            error <= limit,
            "x={x:.17e}, beta={beta:.17e}, actual={actual:.17e}, root={root:.17e}, rho={}",
            error / eta
        );
    }
}

