#!/usr/bin/env python3
"""Generate independent log-target/root fixtures at the large direct-finish gates.

Requires mpmath. References use the Gaussian erfc formula at 160 and 240 decimal digits,
then solve the exact sum of the stored target pair. They do not evaluate the
candidate inverse series. The component cases deliberately place precise()
near a gate, including cases normal whole-solver iteration might skip.
"""
import argparse
import math
from pathlib import Path
import struct
import subprocess
import mpmath as mp

mp.mp.dps = 200
U = mp.mpf(2) ** -53
K = mp.sqrt(2 * mp.pi)
MIN_NORMAL = mp.mpf(2) ** -1022


def bits(value):
    return struct.unpack('<Q', struct.pack('<d', float(value)))[0]


def mills(z):
    return mp.sqrt(mp.pi / 2) * mp.exp(z * z / 2) * mp.erfc(z / mp.sqrt(2))


def geometry(a, x, upper):
    y = mp.sqrt(x*x + 2*a)
    s = 2*a/(y-x) if x < 0 else x+y
    d = mills(x)+mills(y) if upper else mills(-x)-mills(y)
    return y, s, d


def log_value(a, x, upper):
    _, _, d = geometry(a, x, upper)
    return -x*x/2 - mp.log(K) + mp.log(d)


def derivative(a, x, upper):
    y, s, d = geometry(a, x, upper)
    return (-1 if upper else 1)*s/(y*d)


def generate():
    global K
    K = mp.sqrt(2 * mp.pi)
    cases = [
        (math.nextafter(10.0, math.inf), -0.00001, False),
        (math.nextafter(10.0, math.inf), 0.0, False),
        (20.0, math.nextafter(-16.0, -math.inf), False),
        (20.0, -16.0, False),
        (20.0, math.nextafter(-16.0, math.inf), False),
        (math.nextafter(96.0, -math.inf), -8.0, False),
        (96.0, -8.0, False),
        (math.nextafter(96.0, math.inf), -8.0, False),
        (500.0, -5.0, False),
        (1000.0, -0.5, False),
        (math.nextafter(10.0, math.inf), 0.125, True),
        (20.0, 0.5, True),
        (math.nextafter(127.875, -math.inf), 0.5, True),
        (127.875, 0.5, True),
        (math.nextafter(127.875, math.inf), 0.5, True),
        (500.0, 8.0, True),
        (1416.0, 1.0, True),
    ]
    result = []
    for a0, x0, upper in cases:
        a, x = mp.mpf(a0), mp.mpf(x0)
        q0 = log_value(a, x, upper)
        for exponent in [22, 17, 16]:
            gate = mp.mpf(2) ** -exponent
            for sign in [-1, 1]:
                for side in [-1, 0, 1]:
                    residual = sign*gate*(1 + mp.mpf(side)/1024)
                    target = q0-residual
                    th = float(target)
                    tl = float(target-mp.mpf(th))
                    target = mp.mpf(th)+mp.mpf(tl)
                    physical = mp.exp(-a/2)*(1-mp.exp(target) if upper else mp.exp(target))
                    if physical < MIN_NORMAL:
                        continue
                    root_x = mp.findroot(lambda v: log_value(a, v, upper)-target, x,
                                         df=lambda v: derivative(a, v, upper), solver='newton',
                                         tol=mp.eps*1024, maxsteps=30)
                    assert (0 <= root_x <= 16) if upper else (-40 <= root_x <= 1)
                    _, root, d = geometry(a, root_x, upper)
                    rh = float(root)
                    rl = float(root-mp.mpf(rh))
                    # Jaeckel attainable relative error for the physical
                    # normalized price. P/(s*phi(x)) = Dprice/s.
                    price_d = K*mp.exp(root_x*root_x/2)-d if upper else d
                    eta = 2*U*(1+price_d/root)
                    result.append((a0,x0,upper,th,tl,rh,rl,float(eta),exponent,side))
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, default=Path(__file__).resolve().parents[1]/'src/experimental/large_direct_tests.rs')
    args = parser.parse_args()
    mp.mp.dps = 160
    first = generate()
    mp.mp.dps = 240
    records = generate()
    encoded = lambda rows: [tuple(bits(v) if isinstance(v, float) else v for v in row) for row in rows]
    assert encoded(first) == encoded(records), "reference bits differ between 160 and 240 digits"
    lines = [
        '// Generated by scripts/generate_large_direct_seams.py; 160/240-digit erfc/Newton references with identical stored bits.',
        '// Each target is the exact real sum of two binary64 values.',
        'use super::{DD, finish_direct, precise};',
        '',
        '#[test]',
        'fn independent_log_targets_cover_direct_finish_gates_and_mills_seams() {',
        '    // a, x, upper, target hi/lo, root hi/lo, eta_J, gate exponent, gate side.',
        '    #[allow(clippy::type_complexity)]',
        '    #[rustfmt::skip]',
        '    const CASES: &[(u64, u64, bool, u64, u64, u64, u64, u64, i32, i32)] = &[',
    ]
    for a,x,upper,th,tl,rh,rl,eta,exponent,side in records:
        fields = [f'0x{bits(a):016x}',f'0x{bits(x):016x}',str(upper).lower()]
        fields += [f'0x{bits(v):016x}' for v in [th,tl,rh,rl,eta]]
        fields += [str(exponent),str(side)]
        lines.append('        ('+', '.join(fields)+'),')
    lines += [
        '    ];',
        '    for &(a, x, upper, th, tl, rh, rl, eta, exponent, side) in CASES {',
        '        let a = f64::from_bits(a);',
        '        let x = f64::from_bits(x);',
        '        let target = DD { hi: f64::from_bits(th), lo: f64::from_bits(tl) };',
        '        let pe = precise(a, x, target, upper);',
        '        let gate = 2.0_f64.powi(-exponent);',
        '        if side != 0 {',
        '            assert_eq!(pe.residual.hi.abs() <= gate, side < 0, "a={a:e}, x={x:e}, upper={upper}, gate={gate:e}");',
        '        }',
        '        // The outside case verifies the handoff comparison. Its',
        '        // correction is outside this gate\'s certified domain.',
        '        if pe.residual.hi.abs() > gate { continue; }',
        '        let actual = finish_direct(x, pe);',
        '        let root_hi = f64::from_bits(rh);',
        '        let root_lo = f64::from_bits(rl);',
        '        let relative = ((actual-root_hi)-root_lo).abs()/root_hi;',
        '        let rho = relative/f64::from_bits(eta);',
        '        // Exact internal targets also retain the stronger raw relative bound.',
        '        assert!(relative < f64::EPSILON, \"internal relative error={relative:e}, a={a:e}, x={x:e}, upper={upper}, gate={gate:e}\");',
        '        assert!(actual.is_finite() && actual > 0.0 && rho < 1.0, "a={a:e}, x={x:e}, upper={upper}, gate={gate:e}, rho={rho:e}");',
        '    }',
        '}',
    ]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text('\n'.join(lines)+'\n')
    subprocess.run(['rustfmt', '--edition', '2024', str(args.out)], check=True)
    print(f'{len(records)} independent component cases -> {args.out}')


if __name__ == '__main__':
    main()
